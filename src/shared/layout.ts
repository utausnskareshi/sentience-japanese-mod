/**
 * 表示レイアウトの目安（ゲーム内プラグインと作業用CLIの検査で共有する定数）。
 *
 * どちらか一方だけを変えると、検査では問題なしでもゲーム内で溢れる（またはその逆）ため、
 * 値はここで一元管理する。
 */

/** 吹き出し（\pop）1 行の最大文字数の目安（全角換算） */
export const POP_MAX_CHARS = 18;

/** 通常ウィンドウ 1 行の最大文字数の目安（全角換算。読みやすさのための上限） */
export const WINDOW_MAX_CHARS = 46;

/**
 * 通常ウィンドウ 1 ページに表示できる行数（YEP_MessageCore の Default Rows）。
 * これを超えると改ページ（入力待ち）になる。
 */
export const WINDOW_PAGE_LINES = 4;

/** 吹き出しの行数の警告しきい値（吹き出しは改ページせず縦に伸びるため、長すぎると画面からはみ出す） */
export const POP_MAX_LINES = 6;
