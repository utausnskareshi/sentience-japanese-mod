describe('plugins.js への登録', () => {
  const original = '// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n{"name":"A","status":true,"description":"","parameters":{}},\n{"name":"B","status":true,"description":"","parameters":{}}\n];';

  it('配列の末尾にエントリを追加し、他の部分は変えない', () => {
    const patched = addPluginEntry(original);
    expect(patched.startsWith(original.slice(0, original.lastIndexOf('}') + 1))).toBe(true);
    expect(patched.endsWith('\n];')).toBe(true);
    const json = /\$plugins\s*=\s*(\[[\s\S]*\])/.exec(patched)?.[1] ?? '[]';
    const list = JSON.parse(json) as Array<{ name: string }>;
    expect(list.map((p) => p.name)).toEqual(['A', 'B', PLUGIN_ENTRY.name]);
  });

  it('登録済みなら変更しない（冪等）', () => {
    const once = addPluginEntry(original);
    expect(addPluginEntry(once)).toBe(once);
  });

  it('CRLF のファイルでは CRLF で追加する', () => {
    const crlf = original.replace(/\n/g, '\r\n');
    expect(addPluginEntry(crlf)).toContain(`},\r\n{"name":"${PLUGIN_ENTRY.name}"`);
  });

  it('想定外の形式なら理由つきで例外を投げる', () => {
    expect(() => addPluginEntry('var $plugins = null;')).toThrow(/想定と異なる/);
  });
});

describe('ZIP 作成', () => {
  it('UTF-8 のファイル名と Deflate 圧縮で格納し、展開すると元に戻る', () => {
    const text = Buffer.from('こんにちは'.repeat(100), 'utf8');
    const zip = createZip([{ name: 'フォルダ/はじめに.txt', data: text, modified: new Date(2026, 10, 21, 12, 0, 0) }]);
    // ローカルファイルヘッダ
    expect(zip.readUInt32LE(0)).toBe(0x04034b50);
    expect(zip.readUInt16LE(6) & 0x0800).toBe(0x0800);
    expect(zip.readUInt16LE(8)).toBe(8);
    const nameLength = zip.readUInt16LE(26);
    const compressedSize = zip.readUInt32LE(18);
    expect(zip.subarray(30, 30 + nameLength).toString('utf8')).toBe('フォルダ/はじめに.txt');
    const body = zip.subarray(30 + nameLength, 30 + nameLength + compressedSize);
    expect(inflateRawSync(body).equals(text)).toBe(true);
    // 終端レコードのエントリ数
    expect(zip.readUInt16LE(zip.length - 22 + 10)).toBe(1);
  });

  it('複数エントリ（空ファイルを含む）を中央ディレクトリから読み戻せる', () => {
    const modified = new Date(2026, 10, 23, 9, 30, 10);
    const files = [
      { name: 'dir/a.exe', data: Buffer.from(Array.from({ length: 5000 }, (_, i) => i % 251)) },
      { name: 'dir/empty.txt', data: Buffer.alloc(0) },
      { name: 'dir/はじめにお読みください.txt', data: Buffer.from('説明\r\n'.repeat(50), 'utf8') },
    ];
    const zip = createZip(files.map((f) => ({ ...f, modified })));
    const eocd = zip.length - 22;
    expect(zip.readUInt32LE(eocd)).toBe(0x06054b50);
    const count = zip.readUInt16LE(eocd + 10);
    expect(count).toBe(files.length);
    // 一般的な展開処理と同じく、中央ディレクトリをたどって各ファイルを取り出す
    let cursor = zip.readUInt32LE(eocd + 16);
    const restored = Array.from({ length: count }, () => {
      expect(zip.readUInt32LE(cursor)).toBe(0x02014b50);
      const method = zip.readUInt16LE(cursor + 10);
      const crc = zip.readUInt32LE(cursor + 16);
      const compressedSize = zip.readUInt32LE(cursor + 20);
      const size = zip.readUInt32LE(cursor + 24);
      const nameLength = zip.readUInt16LE(cursor + 28);
      const extraLength = zip.readUInt16LE(cursor + 30);
      const commentLength = zip.readUInt16LE(cursor + 32);
      const localOffset = zip.readUInt32LE(cursor + 42);
      const name = zip.subarray(cursor + 46, cursor + 46 + nameLength).toString('utf8');
      cursor += 46 + nameLength + extraLength + commentLength;
      expect(zip.readUInt32LE(localOffset)).toBe(0x04034b50);
      const localNameLength = zip.readUInt16LE(localOffset + 26);
      const localExtraLength = zip.readUInt16LE(localOffset + 28);
      const start = localOffset + 30 + localNameLength + localExtraLength;
      const body = zip.subarray(start, start + compressedSize);
      const data = method === 8 ? inflateRawSync(body) : Buffer.from(body);
      expect(data.length).toBe(size);
      expect(crc32(data)).toBe(crc);
      return { name, data };
    });
    expect(restored.map((r) => r.name)).toEqual(files.map((f) => f.name));
    restored.forEach((r, i) => expect(r.data.equals(files[i]?.data ?? Buffer.alloc(1))).toBe(true));
  });

  // TA-13: 多くの展開ツールは中央ディレクトリ側のフラグを使うため、そちらの UTF-8 フラグも確かめる
  it('中央ディレクトリにも UTF-8 フラグ（ビット 11）を立てる', () => {
    const zip = createZip([{ name: 'はじめに.txt', data: Buffer.from('x'), modified: new Date(Date.UTC(2026, 0, 1)) }]);
    const central = zip.readUInt32LE(zip.length - 22 + 16);
    expect(zip.readUInt32LE(central)).toBe(0x02014b50);
    expect(zip.readUInt16LE(central + 8) & 0x0800).toBe(0x0800);
  });

  // TA-13・TA-07: DOS 日時（既知の日時 → 既知の値）を UTC の成分で、ローカルヘッダと中央ディレクトリの両方に記録する
  it('更新日時を UTC の成分の DOS 日時で記録する（2026-11-21 12:34:56Z → 時刻 0x645C・日付 0x5D75）', () => {
    const modified = new Date(Date.UTC(2026, 10, 21, 12, 34, 56));
    expect(toDosDateTime(modified)).toEqual({ time: 0x645c, day: 0x5d75 });
    const zip = createZip([{ name: 'a.txt', data: Buffer.from('a'), modified }]);
    expect([zip.readUInt16LE(10), zip.readUInt16LE(12)]).toEqual([0x645c, 0x5d75]);
    const central = zip.readUInt32LE(zip.length - 22 + 16);
    expect([zip.readUInt16LE(central + 12), zip.readUInt16LE(central + 14)]).toEqual([0x645c, 0x5d75]);
    // 1980 年より前は 1980 年として記録する（DOS 日時の下限）
    expect(toDosDateTime(new Date(Date.UTC(1979, 0, 2, 0, 0, 0))).day).toBe((0 << 9) | (1 << 5) | 2);
  });

  // TA-07: 同じ入力からは、実行する PC のタイムゾーンに依らず同じバイト列になる
  it('同じ入力からは同じ Zip になり、タイムゾーン（TZ）を変えても変わらない', () => {
    const entries = [
      { name: 'dir/a.exe', data: Buffer.from(Array.from({ length: 3000 }, (_, i) => i % 7)), modified: new Date(Date.UTC(2026, 10, 23, 15, 0, 0)) },
      { name: 'dir/はじめにお読みください.txt', data: Buffer.from('説明\r\n', 'utf8'), modified: new Date(Date.UTC(2026, 10, 23, 15, 0, 0)) },
    ];
    const original = process.env['TZ'];
    try {
      process.env['TZ'] = 'Asia/Tokyo';
      const tokyo = createZip(entries);
      process.env['TZ'] = 'UTC';
      const utc = createZip(entries);
      expect(tokyo.equals(utc)).toBe(true);
      expect(createZip(entries).equals(utc)).toBe(true);
    } finally {
      if (original === undefined) {
        delete process.env['TZ'];
      } else {
        process.env['TZ'] = original;
      }
    }
  });
});

describe('訳文チェック', () => {
  const unit = (source: string, display: SourceUnit['display'] = 'pop'): SourceUnit => ({
    ns: 'msg',
    key: '00000000000000',
    source,
    display,
    order: 0,
    count: 1,
    refs: [],
    scene: 's',
    sceneTitle: 's',
  });

  it('制御文字の個数が一致しなければ指摘する', () => {
    expect(checkTranslation(unit('Hello \\C[2]world\\C[0].'), 'こんにちは、\\C[2]世界\\C[0]。')).toEqual([]);
    const issue = checkTranslation(unit('Hello \\n[3].'), 'こんにちは。')[0];
    expect(issue?.severity).toBe('error');
    expect(issue?.message).toMatch(/制御文字が一致しません/);
  });

  it('日本語が無い訳文と半角カナを指摘する', () => {
    const untranslated = checkTranslation(unit('Hello there.'), 'Hello there.')[0];
    expect(untranslated?.severity).toBe('warning');
    expect(untranslated?.message).toMatch(/未翻訳/);
    const halfWidth = checkTranslation(unit('Hello.'), 'ﾊﾛｰ')[0];
    expect(halfWidth?.severity).toBe('error');
    expect(halfWidth?.message).toMatch(/半角カナ/);
  });

  it('長すぎる吹き出しを指摘する', () => {
    expect(checkTranslation(unit('Long.'), 'あ'.repeat(18 * 7)).some((i) => i.severity === 'warning' && /長すぎます/.test(i.message))).toBe(true);
  });

  it('通常ウィンドウで 4 行を超える文章を警告する（改ページの確認用）', () => {
    const issues = checkTranslation(unit('Long.', 'window'), 'あ'.repeat(46 * 5));
    expect(issues.some((i) => i.severity === 'warning' && /4 行を超えます/.test(i.message))).toBe(true);
    expect(checkTranslation(unit('Short.', 'window'), 'あ'.repeat(46 * 4))).toEqual([]);
  });

  it('訳文に入った吹き出し指定（\\pop）は不一致として検出する', () => {
    const issue = checkTranslation(unit('Hello.'), '\\pop[1]こんにちは。')[0];
    expect(issue?.severity).toBe('error');
    expect(issue?.message).toMatch(/制御文字が一致しません/);
  });

  // TA-13: 同じ制御文字の個数の違い（原文には \N[1] が複数回の文が多い）と、文字どおりの \（\\）も数える
  it('同じ制御文字の個数が減った訳文と、\\\\（文字どおりの \\）の欠落を指摘する', () => {
    const twice = unit('\\N[1], \\N[1]!');
    expect(checkTranslation(twice, '\\N[1]、\\N[1]！')).toEqual([]);
    const fewer = checkTranslation(twice, '\\N[1]！')[0];
    expect(fewer?.severity).toBe('error');
    expect(fewer?.message).toMatch(/\\N\[1\]（原文 2 \/ 訳文 1）/);
    const backslash = unit('C:\\\\Data');
    expect(checkTranslation(backslash, 'C:\\\\データ')).toEqual([]);
    expect(checkTranslation(backslash, 'C:データ')[0]?.message).toMatch(/制御文字が一致しません/);
  });

  // TA-13: 半角カナは句読点・濁点（範囲の両端付近）も対象
  it('半角の句点「｡」・濁点「ﾞ」も半角カナとして指摘する', () => {
    ['ﾊﾛｰ', 'こんにちは｡', 'ﾀﾞ'].forEach((text) =>
      expect(checkTranslation(unit('Hello.'), text).some((i) => i.severity === 'error' && /半角カナ/.test(i.message)), text).toBe(true),
    );
  });
});

describe('訳文の文字・改行・空行の検査（TA-03・TA-04・TA-14）', () => {
  /** 名前空間・表示種別・出現箇所を指定して単位を作る（架空のデータ） */
  const unitOf = (ns: SourceUnit['ns'], display: SourceUnit['display'], source: string, wheres: readonly string[] = ['x']): SourceUnit => ({
    ns,
    key: '00000000000000',
    source,
    display,
    order: 0,
    count: wheres.length,
    refs: wheres.map((where) => ({ file: 'f.json', where })),
    scene: 's',
    sceneTitle: 's',
  });
  const errorsOf = (u: SourceUnit, text: string): string[] => checkTranslation(u, text).filter((i) => i.severity === 'error').map((i) => i.message);
  const warningsOf = (u: SourceUnit, text: string): string[] => checkTranslation(u, text).filter((i) => i.severity === 'warning').map((i) => i.message);
  const pop = unitOf('msg', 'pop', 'Hello.\nWorld.');

  it('改行以外の C0 制御文字（改ページ・ESC・BS・タブ・NUL）と DEL を error にし、文字を U+XXXX で示す', () => {
    const cases: ReadonlyArray<readonly [string, string]> = [
      ['これは\x0cb強調\x0cbのテストです。', 'U+000C'],
      ['色が\x1bC[2]変わる\x1bC[0]テスト。', 'U+001B'],
      ['制御\x08文字のテスト。', 'U+0008'],
      ['タブ\tです。', 'U+0009'],
      ['ヌル\x00です。', 'U+0000'],
      ['削除\x7fです。', 'U+007F'],
    ];
    cases.forEach(([text, code]) => {
      const errors = errorsOf(pop, text);
      expect(errors.some((m) => m.includes(code) && /制御用の文字/.test(m)), text).toBe(true);
    });
    // 改行（\n）だけなら問題なし
    expect(checkTranslation(pop, 'こんにちは。\n世界。')).toEqual([]);
    expect(checkCharacters('こんにちは。\n世界。')).toEqual([]);
  });

  it('文字化けの痕跡（U+FFFD）を error にする', () => {
    const garbled = `回復${String.fromCharCode(0xfffd)}アイテム`;
    expect(errorsOf(pop, garbled).some((m) => /U\+FFFD/.test(m))).toBe(true);
    expect(checkCharacters(garbled).map((i) => i.severity)).toEqual(['error']);
  });

  it('1 行で表示される項目（選択肢・項目名・マップ名・名前・用語など）の改行を error にする', () => {
    const singleLine = [
      unitOf('choice', 'choice', 'Yes.'),
      unitOf('cem', 'menu', 'Dea', ['[55].name']),
      unitOf('map', 'map', 'Hangar', ['displayName']),
      unitOf('name', 'name', 'Dea', ['[1].name']),
      unitOf('db', 'item', 'Potion', ['[1].name']),
      unitOf('db', 'item', '%1 is poisoned!', ['[4].message1']),
      unitOf('term', 'term', 'Item', ['terms.commands[4]']),
      unitOf('term', 'menu', 'Area Map', ['YEP_MainMenuManager.Menu 79 Name']),
      unitOf('quest', 'quest', 'Main Quest', ['[1].name']),
      unitOf('quest', 'quest', 'Main', ['[0][1]']),
      // 説明と名前の両方に使われる訳文は、名前の表示が崩れるため改行できない
      unitOf('db', 'item', 'Keycard', ['[2].name', '[3].description']),
    ];
    singleLine.forEach((u) => {
      expect(allowsLineBreaks(u), `${u.ns}/${u.display}`).toBe(false);
      expect(errorsOf(u, '一行目\n二行目').some((m) => /1 行で表示される項目/.test(m)), `${u.ns}/${u.display}`).toBe(true);
      expect(errorsOf(u, '一行目'), `${u.ns}/${u.display}`).toEqual([]);
    });
  });

  it('複数行で表示される項目（文章・説明文・クエストの説明と手順・プロフィールなど）の改行は許す', () => {
    const multiLine = [
      unitOf('msg', 'window', 'Hello.'),
      unitOf('msg', 'scroll', 'Hello.'),
      unitOf('cem', 'subtext', 'An android.\nVery kind.', ['[55].<Subtext>']),
      unitOf('db', 'item', 'Restores HP.', ['[1].description']),
      unitOf('name', 'name', 'A kind android.', ['[1].profile']),
      // イベントコマンドの名前・二つ名・プロフィールの変更は、どれか区別できないため許す
      unitOf('name', 'name', 'A kind android.', ['EV6 p0 #12']),
      unitOf('quest', 'quest', 'Find the core.', ['[1].desc']),
      unitOf('quest', 'quest', 'Go north.', ['[1].steps[0][0]', '[2].desc']),
      unitOf('term', 'term', 'Subtext here!', ['YEP_CommonEventMenu.Default Subtext']),
      unitOf('term', 'term', 'Help.', ['YEP_CommonEventMenu.Default Help']),
    ];
    multiLine.forEach((u) => {
      expect(allowsLineBreaks(u), `${u.ns}/${u.display}`).toBe(true);
      expect(errorsOf(u, '一行目\n二行目'), `${u.ns}/${u.display}`).toEqual([]);
    });
  });

  it('原文に無い先頭の空行・末尾の空行・3 行以上の連続した空行を警告する（TA-14）', () => {
    expect(warningsOf(pop, '\nこんにちは。')).toEqual(['原文に無い空行が先頭にあります']);
    expect(warningsOf(pop, 'こんにちは。\n')).toEqual(['末尾に空行があります']);
    expect(warningsOf(pop, 'あ\n\n\n\nい')).toEqual(['空行が 3 行続いています（原文に無い連続した空行）']);
    // 2 行までの空行・原文と同じ形の空行は警告しない
    expect(warningsOf(pop, 'あ\n\n\nい')).toEqual([]);
    expect(warningsOf(unitOf('msg', 'window', '\nDay 2'), '\n2 日目')).toEqual([]);
    // （行数の警告が出ないよう、行数を検査しないスクロール文章で確かめる）
    expect(warningsOf(unitOf('msg', 'scroll', 'A\n\n\n\n\n\nB'), 'あ\n\n\n\n\n\nい')).toEqual([]);
  });
});
