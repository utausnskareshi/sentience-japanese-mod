using System.Text;
using SentienceJP.Core.Plugins;
using SentienceJP.Core.Tests.TestSupport;

namespace SentienceJP.Core.Tests.Plugins;

/// <summary>plugins.js の解析・挿入・除去のテスト。</summary>
public sealed class PluginsJsEditorTests
{
    private const string Entry = FakeGame.PluginEntryJson;

    [Fact]
    public void Parse_SampleFormat_FindsElementsAndNames()
    {
        var document = PluginsJsEditor.Parse(FakeGame.SamplePluginsJs);

        Assert.Equal(["PluginA", "PluginB", "PluginC"], document.Elements.Select(e => e.Name));
        Assert.Equal("\n", document.NewLine);
        Assert.True(document.Contains("PluginB"));
        Assert.False(document.Contains(GameConstants.PluginName));
    }

    [Fact]
    public void InsertEntry_AppendsAtEndAndKeepsOtherTextIntact()
    {
        var result = PluginsJsEditor.InsertEntry(FakeGame.SamplePluginsJs, Entry);

        var document = PluginsJsEditor.Parse(result);
        Assert.Equal(GameConstants.PluginName, document.Elements[^1].Name);

        // 元の最後の要素の直後に ",\n<entry>" が入るだけで、それ以外は変わらない
        var lastEnd = PluginsJsEditor.Parse(FakeGame.SamplePluginsJs).Elements[^1].End;
        Assert.Equal(FakeGame.SamplePluginsJs[..lastEnd] + ",\n" + Entry + FakeGame.SamplePluginsJs[lastEnd..], result);
        Assert.EndsWith("\n];\n", result, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void InsertThenRemove_RoundTripsExactly(bool useCrlf)
    {
        var original = useCrlf ? FakeGame.SamplePluginsJs.Replace("\n", "\r\n", StringComparison.Ordinal) : FakeGame.SamplePluginsJs;

        var inserted = PluginsJsEditor.InsertEntry(original, Entry);
        var (removed, changed) = PluginsJsEditor.RemoveEntry(inserted, GameConstants.PluginName);

        Assert.True(changed);
        Assert.Equal(original, removed);
        Assert.Contains(useCrlf ? ",\r\n" + Entry : ",\n" + Entry, inserted, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("var $plugins =\n[\n];\n")]
    [InlineData("var $plugins =\n[];\n")]
    public void InsertThenRemove_EmptyArray_RoundTripsExactly(string original)
    {
        var inserted = PluginsJsEditor.InsertEntry(original, Entry);
        Assert.Single(PluginsJsEditor.Parse(inserted).Elements);

        var (removed, _) = PluginsJsEditor.RemoveEntry(inserted, GameConstants.PluginName);
        Assert.Equal(original, removed);
    }

    [Fact]
    public void InsertEntry_AlreadyPresent_Throws()
    {
        var inserted = PluginsJsEditor.InsertEntry(FakeGame.SamplePluginsJs, Entry);

        var ex = Assert.Throws<PluginsJsFormatException>(() => PluginsJsEditor.InsertEntry(inserted, Entry));
        Assert.Contains("既に", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void RemoveEntry_Absent_ReturnsUnchanged()
    {
        var (text, changed) = PluginsJsEditor.RemoveEntry(FakeGame.SamplePluginsJs, GameConstants.PluginName);

        Assert.False(changed);
        Assert.Equal(FakeGame.SamplePluginsJs, text);
    }

    [Fact]
    public void RemoveEntry_InMiddle_RemovesOnlyThatEntry()
    {
        var (text, changed) = PluginsJsEditor.RemoveEntry(FakeGame.SamplePluginsJs, "PluginB");

        Assert.True(changed);
        Assert.Equal(["PluginA", "PluginC"], PluginsJsEditor.Parse(text).Elements.Select(e => e.Name));
        Assert.DoesNotContain("PluginB", text, StringComparison.Ordinal);
    }

    [Fact]
    public void RemoveEntry_FirstWithFollowers_KeepsFormat()
    {
        var (text, _) = PluginsJsEditor.RemoveEntry(FakeGame.SamplePluginsJs, "PluginA");

        Assert.StartsWith("// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n{\"name\":\"PluginB\"", text, StringComparison.Ordinal);
    }

    [Fact]
    public void RemoveEntry_DuplicateEntries_RemovesAll()
    {
        var once = PluginsJsEditor.InsertEntry(FakeGame.SamplePluginsJs, Entry);

        // 異常系: 手作業などで同じエントリが 2 つ入ってしまった場合
        var twice = once.Replace("\n];", ",\n" + Entry + "\n];", StringComparison.Ordinal);
        Assert.Equal(2, PluginsJsEditor.Parse(twice).Elements.Count(e => e.Name == GameConstants.PluginName));

        var (removed, _) = PluginsJsEditor.RemoveEntry(twice, GameConstants.PluginName);
        Assert.Equal(FakeGame.SamplePluginsJs, removed);
    }

    [Theory]
    [InlineData("var x = [];", "var $plugins")]
    [InlineData("var $plugins = {};", "配列")]
    [InlineData("var $plugins =\n[\n{\"name\":\"A\"}\n", "閉じられていません")]
    [InlineData("var $plugins =\n[\n{\"name\":\"A\"},\n];\n", "JSON として不正")]
    [InlineData("var $plugins =\n[\n{\"name\":\"A\"} {\"name\":\"B\"}\n];\n", "',' が抜けています")]
    [InlineData("var $plugins =\n[\n{\"name\":\"A\",\"d\":\"unterminated}\n];\n", "閉じられていません")]
    public void Parse_InvalidFormat_ThrowsWithMessage(string text, string expectedFragment)
    {
        var ex = Assert.Throws<PluginsJsFormatException>(() => PluginsJsEditor.Parse(text));
        Assert.Contains(expectedFragment, ex.Message, StringComparison.Ordinal);
    }

    /// <summary>テスト用の 1 要素（PluginA）。</summary>
    private const string ElementA = "{\"name\":\"A\",\"status\":true,\"description\":\"\",\"parameters\":{}}";

    [Fact]
    public void Parse_RealGameHeaderFormat_FindsDeclarationAfterTwoCommentLines()
    {
        // CA-06: 実ゲームの先頭形式（"// Generated by RPG Maker." の 2 行コメント＋宣言）
        var declarations = PluginsJsDeclarationScanner.FindDeclarations(FakeGame.SamplePluginsJs);

        var declaration = Assert.Single(declarations);
        Assert.Equal(FakeGame.SamplePluginsJs.IndexOf("var $plugins", StringComparison.Ordinal), declaration.Start);
        Assert.Equal(declaration.Start + "var $plugins".Length, declaration.NameEnd);
    }

    [Theory]
    [InlineData("var $plugins=[" + ElementA + "];")]
    [InlineData("var $plugins=[{\"name\":\"A\",\"status\":true,\"description\":\"x]}//\\\"'`/*\",\"parameters\":{}}];")]
    [InlineData("var\t$plugins\n=\n[\n" + ElementA + "\n];\n")]
    [InlineData("var $plugins /* プラグインの一覧 */ = // 改行の前のコメント\n[\n" + ElementA + "\n];\n")]
    public void Parse_CompactOrSpacedDeclaration_InsertThenRemoveRoundTrips(string original)
    {
        // CA-06: 1 行に圧縮した形式（var $plugins=[...]）や、宣言の途中の空白・コメントも受け付け、挿入→除去でバイト一致に戻る
        Assert.Equal(["A"], PluginsJsEditor.Parse(original).Elements.Select(e => e.Name));

        var inserted = PluginsJsEditor.InsertEntry(original, Entry);
        var (removed, changed) = PluginsJsEditor.RemoveEntry(inserted, GameConstants.PluginName);

        Assert.True(changed);
        Assert.Equal(original, removed);
    }

    [Theory]
    [InlineData("// Generated by RPG Maker.\n// var $plugins = [] is overwritten by the editor. Do not edit.\nvar $plugins =\n[\n" + ElementA + "\n];\n")]
    [InlineData("/* var $plugins = [\n{\"name\":\"Fake\"}\n] */\nvar $plugins =\n[\n" + ElementA + "\n];\n")]
    [InlineData("var note = 'var $plugins = [] is generated';\nvar $plugins =\n[\n" + ElementA + "\n];\n")]
    [InlineData("var note = \"var $plugins = [\";\nvar $plugins =\n[\n" + ElementA + "\n];\n")]
    [InlineData("var note = 'it\\'s var $plugins = [';\nvar $plugins =\n[\n" + ElementA + "\n];\n")]
    [InlineData("var note = `var $plugins = [${'var $plugins = ['}] ${ {a: `var $plugins = [`}.a }`;\nvar $plugins =\n[\n" + ElementA + "\n];\n")]
    [InlineData("var $plugins =\n[\n{\"name\":\"A\",\"status\":true,\"description\":\"var $plugins = [\",\"parameters\":{}}\n];\n// var $plugins = [] after\n")]
    [InlineData("var $plugins_extra = [1];\nvar $plugins =\n[\n" + ElementA + "\n];\nvar myvar = 1; variable$plugins = 2;\n")]
    public void Parse_MarkerInCommentOrStringOrSimilarName_UsesOnlyTheRealDeclaration(string original)
    {
        // CA-06: コメント（// と /* */）・文字列リテラル（' " `）の中の "var $plugins = [" や、似た名前の変数は宣言として数えない。
        // 挿入は本物の配列に入り、他の文字（コメントの行など）には触れず、除去でバイト一致に戻る
        var document = PluginsJsEditor.Parse(original);
        Assert.Equal(["A"], document.Elements.Select(e => e.Name));

        var inserted = PluginsJsEditor.InsertEntry(original, Entry);
        var reparsed = PluginsJsEditor.Parse(inserted);
        Assert.Equal(["A", GameConstants.PluginName], reparsed.Elements.Select(e => e.Name));
        Assert.Equal(original[..document.Elements[^1].End], inserted[..document.Elements[^1].End]);

        var (removed, _) = PluginsJsEditor.RemoveEntry(inserted, GameConstants.PluginName);
        Assert.Equal(original, removed);
    }

    [Theory]
    [InlineData("var $plugins = [];\nvar $plugins = [];\n")]
    [InlineData("var $plugins = [" + ElementA + "];\nfunction f() { var $plugins = []; }\n")]
    public void Parse_TwoCodeDeclarations_IsFormatError(string text)
    {
        // CA-06: コードとしての宣言が 2 つ以上あれば、どれがプラグインの一覧か判断できないため形式エラーにする
        var ex = Assert.Throws<PluginsJsFormatException>(() => PluginsJsEditor.Parse(text));

        Assert.Contains("2 個", ex.Message, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("/* 閉じないコメント\nvar $plugins = [];\n", "ブロックコメント")]
    [InlineData("var note = 'abc\nvar $plugins = [];\n", "文字列リテラル")]
    [InlineData("var t = `abc ${ 1 }\nvar $plugins = [];\n", "テンプレート")]
    [InlineData("var t = `${ '}' ;\nvar $plugins = [];\n", "テンプレート")]
    public void Parse_UnterminatedCommentOrString_IsFormatError(string text, string expectedFragment)
    {
        var ex = Assert.Throws<PluginsJsFormatException>(() => PluginsJsEditor.Parse(text));

        Assert.Contains(expectedFragment, ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void FindDeclarations_DeeplyNestedTemplates_DoesNotOverflowTheStack()
    {
        // CA-06: 入れ子は明示的な積み重ねで扱うため、10 万段のテンプレートリテラルでもスタックを使い切らずに形式エラーになる
        var text = string.Concat(Enumerable.Repeat("`${", 100_000)) + "\nvar $plugins = [];";

        Assert.Throws<PluginsJsFormatException>(() => PluginsJsDeclarationScanner.FindDeclarations(text));
    }

    [Fact]
    public void InsertEntry_InvalidEntryJson_Throws()
    {
        Assert.Throws<PluginsJsFormatException>(() => PluginsJsEditor.InsertEntry(FakeGame.SamplePluginsJs, "{\"status\":true}"));
        Assert.Throws<PluginsJsFormatException>(() => PluginsJsEditor.InsertEntry(FakeGame.SamplePluginsJs, "not json"));
    }

    [RealGameFact]
    public void RealGamePluginsJs_InsertThenRemove_RoundTripsByteForByte()
    {
        // 実ゲームのファイルは読み取りのみ（書き込みは一切しない）
        var bytes = File.ReadAllBytes(RealGameFactAttribute.RealPluginsJsPath);
        var (text, hasBom) = Utf8Text.Decode(bytes, "plugins.js");

        var document = PluginsJsEditor.Parse(text);
        Assert.Equal(18, document.Elements.Count);
        Assert.Equal("OrangeGreenworks", document.Elements[^1].Name);

        var inserted = PluginsJsEditor.InsertEntry(text, Entry);
        var (removed, _) = PluginsJsEditor.RemoveEntry(inserted, GameConstants.PluginName);
        Assert.Equal(bytes, Utf8Text.Encode(removed, hasBom));
    }

    [Fact]
    public void Utf8Text_WithBom_RoundTrips()
    {
        var bytes = new byte[] { 0xEF, 0xBB, 0xBF }.Concat(Encoding.UTF8.GetBytes("var $plugins =\n[];\n日本語")).ToArray();

        var (text, hasBom) = Utf8Text.Decode(bytes, "test");

        Assert.True(hasBom);
        Assert.Equal(bytes, Utf8Text.Encode(text, hasBom));
    }

    [Fact]
    public void Utf8Text_InvalidBytes_Throws()
    {
        var ex = Assert.Throws<PatchException>(() => Utf8Text.Decode([0x76, 0xFF, 0xFE, 0x61], "plugins.js"));
        Assert.Contains("UTF-8", ex.Message, StringComparison.Ordinal);
    }
}
