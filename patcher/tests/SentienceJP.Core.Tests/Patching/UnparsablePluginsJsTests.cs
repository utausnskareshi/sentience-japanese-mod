using System.Text;
using SentienceJP.Core.Patching;
using SentienceJP.Core.Payload;
using SentienceJP.Core.Tests.TestSupport;

namespace SentienceJP.Core.Tests.Patching;

/// <summary>
/// 「解析できないが破損ではない」plugins.js（JavaScript としては正しいが厳密な JSON でない。Steam の更新や他の MOD が書いた新しい内容）の扱いを確かめる結合テスト。
/// - CA-07: 破損らしい場合（長さ 0・NUL・UTF-8 不正）に限ってバックアップで上書きし、正しいテキストは古い内容で上書きしない。
/// - CA-08: 未適用のゲームで、根拠が plugins.js の問題（解析できない・読めない・無い）だけなら「不整合」ではなく専用の状態にし、
///   主ボタンは再確認、案内は理由に応じた文言にする。
/// </summary>
public sealed class UnparsablePluginsJsTests : IDisposable
{
    /// <summary>新しい版の plugins.js（JS としては正しいが末尾カンマがあり、このツールの解析器は拒否する。パッチの登録は無い）。</summary>
    private const string NewLenientPluginsJs =
        "// Generated by RPG Maker.\n" +
        "var $plugins =\n" +
        "[\n" +
        "{\"name\":\"PluginA\",\"status\":true,\"description\":\"\",\"parameters\":{}},\n" +
        "{\"name\":\"NewPluginInUpdate\",\"status\":true,\"description\":\"\",\"parameters\":{}},\n" +
        "];\n";

    private readonly TempDirectory _temp = new();
    private readonly string _game;
    private readonly PayloadBundle _payload;
    private readonly List<string> _log = [];

    /// <summary>偽のゲームとペイロードを用意する。</summary>
    public UnparsablePluginsJsTests()
    {
        _game = FakeGame.CreateGame(_temp.Combine("game"));
        _payload = FakeGame.CreatePayload(_temp.Combine("payload"));
    }

    /// <inheritdoc />
    public void Dispose() => _temp.Dispose();

    [Fact]
    public void ApplyRollback_KeepsExternallyWrittenLenientPluginsJs()
    {
        // CA-07: 適用中（状態ファイル記録の直後）に外部が「厳密な JSON でない新しい plugins.js」へ置き換えた場合、
        // 検証失敗の取り消しで、その新しい内容を適用前の古い内容で上書きしない（以前は上書きして「元の状態に戻しました」と表示していた）
        var fileSystem = new FaultInjectingFileSystem
        {
            After = (kind, path) =>
            {
                if (kind == FileOperationKind.ReplaceFile && path.EndsWith(GameConstants.StateFileName, StringComparison.OrdinalIgnoreCase))
                {
                    File.WriteAllText(PluginsPath, NewLenientPluginsJs, new UTF8Encoding(false));
                }
            },
        };

        var result = PatchApplier.Apply(_game, null, _payload, _log.Add, TimeProvider.System, fileSystem);

        Assert.False(result.Success);
        Assert.Empty(result.CleanupErrors);
        Assert.Equal(NewLenientPluginsJs, File.ReadAllText(PluginsPath));
        Assert.Contains(_log, line => line.Contains("そのままにします", StringComparison.Ordinal));
        Assert.False(Directory.Exists(Full(GameConstants.BackupDirectoryName)));
        Assert.False(Directory.Exists(Full(GameConstants.PatchDataDirectoryRelativePath)));
        Assert.False(File.Exists(Full(GameConstants.PluginFileRelativePath)));
    }

    [Fact]
    public void Restore_AfterSteamUpdateToLenientPluginsJs_KeepsTheNewVersion()
    {
        // CA-07: 適用後に Steam の更新で厳密でない新しい plugins.js（パッチの登録なし）になった場合、元に戻すは古いバックアップで上書きせず、
        // パッチのファイルとバックアップだけを片付ける
        Assert.True(PatchApplier.Apply(_game, null, _payload, _log.Add).Success);
        File.WriteAllText(PluginsPath, NewLenientPluginsJs, new UTF8Encoding(false));
        var status = Detect();
        Assert.Equal(PatchStatusKind.Inconsistent, status.Kind);

        var result = PatchRestorer.Restore(_game, _payload.Manifest, _log.Add);

        Assert.True(result.Success, result.Message);
        Assert.Equal(NewLenientPluginsJs, File.ReadAllText(PluginsPath));
        Assert.False(Directory.Exists(Full(GameConstants.BackupDirectoryName)));
        Assert.False(Directory.Exists(Full(GameConstants.PatchDataDirectoryRelativePath)));
        Assert.False(File.Exists(Full(GameConstants.PluginFileRelativePath)));
    }

    [Fact]
    public void Restore_LenientPluginsJsStillMentioningPlugin_IsUnrecoverableWithGuidance_AndChangesNothing()
    {
        // CA-07: 解析できない正しいテキストにプラグイン名が含まれる（登録が残っている可能性がある）場合は、自動では戻さず案内して中止する
        Assert.True(PatchApplier.Apply(_game, null, _payload, _log.Add).Success);
        var lenientWithEntry = File.ReadAllText(PluginsPath).Replace("\n];", ",\n];", StringComparison.Ordinal);
        File.WriteAllText(PluginsPath, lenientWithEntry, new UTF8Encoding(false));
        var before = DirectorySnapshot.Capture(_game);

        var result = PatchRestorer.Restore(_game, _payload.Manifest, _log.Add);

        Assert.False(result.Success);
        Assert.Contains(GameConstants.PluginName, result.Message, StringComparison.Ordinal);
        Assert.Contains("整合性を確認", result.Message, StringComparison.Ordinal);
        Assert.Empty(DirectorySnapshot.Diff(before, DirectorySnapshot.Capture(_game)));
    }

    [Theory]
    [InlineData("zeros")]
    [InlineData("empty")]
    [InlineData("invalid-utf8")]
    public void Restore_CorruptLookingPluginsJs_StillUsesBackup(string corruption)
    {
        // CA-07: 破損らしい場合（ゼロ埋め・長さ 0・UTF-8 として不正）は、従来どおり記録と一致するバックアップで戻す（C-04 を保つ）
        var before = DirectorySnapshot.Capture(_game);
        Assert.True(PatchApplier.Apply(_game, null, _payload, _log.Add).Success);
        var length = (int)new FileInfo(PluginsPath).Length;
        File.WriteAllBytes(PluginsPath, corruption switch
        {
            "zeros" => new byte[length],
            "empty" => [],
            _ => [.. Encoding.UTF8.GetBytes("var $plugins = ["), 0xFF, 0xFE, .. Encoding.UTF8.GetBytes("];")],
        });

        var result = PatchRestorer.Restore(_game, _payload.Manifest, _log.Add);

        Assert.True(result.Success, result.Message);
        Assert.Contains(_log, line => line.Contains("解析できないため", StringComparison.Ordinal));
        Assert.Empty(DirectorySnapshot.Diff(before, DirectorySnapshot.Capture(_game)));
    }

    [Theory]
    [InlineData("var $plugins =\n[\n{\"name\":\"A\",\"status\":true,\"description\":\"\",\"parameters\":{}},\n];\n")]
    [InlineData("var $plugins =\n[\n// {\"name\":\"Disabled\"},\n{\"name\":\"A\",\"status\":true,\"description\":\"\",\"parameters\":{}}\n];\n")]
    public void VanillaGameWithLenientPluginsJs_IsPluginsJsUnusable_NotInconsistent(string pluginsJs)
    {
        // CA-08: 未適用のゲームで plugins.js が JS としては正しいが厳密でない（末尾カンマ・配列内のコメント）だけなら、
        // 「不整合（パッチのファイルが一部残っています）」ではなく専用の状態にし、主ボタンは「再確認する」にする
        File.WriteAllText(PluginsPath, pluginsJs, new UTF8Encoding(false));

        var status = Detect();
        var plan = PatchOperations.PlanFor(status);

        Assert.Equal(PatchStatusKind.PluginsJsUnusable, status.Kind);
        Assert.Null(plan.MainAction);
        Assert.Equal(PatchScreenPlanner.RecheckLabel, plan.MainLabel);
        Assert.False(plan.ShowSecondaryRestore);
        Assert.Contains("plugins.js", plan.StatusLabel, StringComparison.Ordinal);
        Assert.DoesNotContain("パッチのファイルが一部残っています", plan.StatusLabel, StringComparison.Ordinal);
        Assert.Contains(status.Reasons, r => r.Contains("整合性を確認", StringComparison.Ordinal) && r.Contains("編集は消えます", StringComparison.Ordinal));
    }

    [Fact]
    public void VanillaGameWithLockedPluginsJs_IsPluginsJsUnusable_WithUnreadableGuidance()
    {
        // CA-08: 読めない（他のプログラムが排他で開いている・アクセス拒否）だけなら、閉じる・権限を確認する案内にする（整合性の確認は勧めない）
        using (new FileStream(PluginsPath, FileMode.Open, FileAccess.Read, FileShare.None))
        {
            var status = Detect();

            Assert.Equal(PatchStatusKind.PluginsJsUnusable, status.Kind);
            Assert.Contains(status.Reasons, r => r.Contains("読み取れません", StringComparison.Ordinal));
            Assert.Contains(status.Reasons, r => r.Contains("開いているプログラム", StringComparison.Ordinal));
            Assert.DoesNotContain(status.Reasons, r => r.Contains("整合性を確認", StringComparison.Ordinal));
        }
    }

    [Fact]
    public void VanillaGameWithoutPluginsJs_IsPluginsJsUnusable_WithSteamVerifyGuidance()
    {
        File.Delete(PluginsPath);

        var status = Detect();

        Assert.Equal(PatchStatusKind.PluginsJsUnusable, status.Kind);
        Assert.Contains(status.Reasons, r => r.Contains("plugins.js がありません", StringComparison.Ordinal));
        Assert.Contains(status.Reasons, r => r.Contains("整合性を確認", StringComparison.Ordinal) && r.Contains("編集は消えます", StringComparison.Ordinal));
    }

    [Fact]
    public void LenientPluginsJsWithPatchTraces_IsStillInconsistent()
    {
        // CA-08: パッチの痕跡（追加ファイル）があれば、従来どおり「不整合」として片付けを促す（plugins.js の問題も根拠に並べる）
        File.WriteAllText(PluginsPath, NewLenientPluginsJs, new UTF8Encoding(false));
        FakeGame.WriteText(_game, GameConstants.PluginFileRelativePath, "// leftover");

        var status = Detect();

        Assert.Equal(PatchStatusKind.Inconsistent, status.Kind);
        Assert.Contains(status.Reasons, r => r.Contains(GameConstants.PluginFileRelativePath, StringComparison.Ordinal));
        Assert.Contains(status.Reasons, r => r.Contains("JSON", StringComparison.Ordinal));
    }

    [Fact]
    public void RestoreAfterSteamUpdateToLenientPluginsJs_EndsInPluginsJsUnusable()
    {
        // CA-07 と CA-08: 片付けの後は、パッチの痕跡が無く plugins.js を解析できないだけの状態になる
        Assert.True(PatchApplier.Apply(_game, null, _payload, _log.Add).Success);
        File.WriteAllText(PluginsPath, NewLenientPluginsJs, new UTF8Encoding(false));
        Assert.True(PatchRestorer.Restore(_game, _payload.Manifest, _log.Add).Success);

        Assert.Equal(PatchStatusKind.PluginsJsUnusable, Detect().Kind);
    }

    /// <summary>plugins.js のフルパス。</summary>
    private string PluginsPath => Full(GameConstants.PluginsJsRelativePath);

    /// <summary>ゲームフォルダ配下のフルパス。</summary>
    private string Full(string relativePath) => GamePaths.ToFullPath(_game, relativePath);

    /// <summary>現在の状態を判定する。</summary>
    private PatchStatus Detect() => PatchStatusDetector.Detect(GameSnapshotReader.Read(_game, _payload.Manifest), _payload.Manifest);
}
